"""Regenerate frontend/src/three/isoNumeric.ts: ISO 3166 numeric code (as used by the world-atlas map) → alpha-3.

Run from backend/:  uv run python tools/generate_iso_numeric.py
"""
from pathlib import Path

import pycountry


def main():
    pairs = sorted((c.numeric, c.alpha_3) for c in pycountry.countries)
    lines = ["// ISO 3166-1 numeric → alpha-3. Generated by backend/tools/generate_iso_numeric.py.",
             "export const ISO_NUMERIC: Record<string, string> = {"]
    lines += [f'  "{numeric}": "{alpha3}",' for numeric, alpha3 in pairs]
    lines.append("};")
    target = Path(__file__).resolve().parents[2] / "frontend" / "src" / "three" / "isoNumeric.ts"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    print(f"Wrote {len(pairs)} codes to {target}")


if __name__ == "__main__":
    main()
