"""Regenerate dla/country_names.py from ISO 3166 (pycountry) plus short-name overrides.

Run from backend/:  uv run python tools/generate_country_names.py
"""
from pathlib import Path

import pycountry

# Short names for codes whose official name is long, plus codes that are not current ISO countries
OVERRIDES = {
    "BOL": "Bolivia", "COD": "DR Congo", "CSK": "Czechoslovakia", "DDR": "East Germany",
    "EU": "European Union", "FSM": "Micronesia", "GBR": "United Kingdom", "IRN": "Iran",
    "KOR": "South Korea", "LAO": "Laos", "MDA": "Moldova", "PRK": "North Korea", "PSE": "Palestine",
    "RUS": "Russia", "SUN": "Soviet Union", "SYR": "Syria", "TUR": "Türkiye", "TWN": "Taiwan",
    "TZA": "Tanzania", "USA": "United States", "VAT": "Holy See", "VEN": "Venezuela", "VNM": "Vietnam",
    "YMD": "South Yemen", "YUG": "Yugoslavia",
}


def main():
    names = {c.alpha_3: getattr(c, "common_name", None) or c.name for c in pycountry.countries}
    names.update(OVERRIDES)
    lines = ['"""ISO 3166 alpha-3 code -> short English name. Generated by tools/generate_country_names.py."""',
             "", "COUNTRY_NAMES = {"]
    lines += [f"    {code!r}: {name!r}," for code, name in sorted(names.items())]
    lines.append("}")
    target = Path(__file__).resolve().parents[1] / "dla" / "country_names.py"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(names)} names to {target}")


if __name__ == "__main__":
    main()
