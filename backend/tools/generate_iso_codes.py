"""Regenerate frontend/src/three/isoCodes.ts from ISO 3166 (pycountry).

ISO_NUMERIC: numeric code (used by the world-atlas map) → alpha-3 (used by the UN corpus).
ISO_ALPHA2: alpha-3 → alpha-2 (used by the flag-icons flags).

Run from backend/:  uv run python tools/generate_iso_codes.py
"""
from pathlib import Path

import pycountry

# Not ISO countries, but in the corpus and in flag-icons
EXTRA_ALPHA2 = {"EU": "eu"}


def main():
    countries = list(pycountry.countries)
    lines = ["// ISO 3166-1 code tables. Generated by backend/tools/generate_iso_codes.py.", "",
             "/** numeric (world-atlas map) → alpha-3 (UN corpus) */",
             "export const ISO_NUMERIC: Record<string, string> = {"]
    lines += [f'  "{c.numeric}": "{c.alpha_3}",' for c in sorted(countries, key=lambda c: c.numeric)]
    lines += ["};", "", "/** alpha-3 (UN corpus) → lower-case alpha-2 (flag-icons file names) */",
              "export const ISO_ALPHA2: Record<string, string> = {"]
    pairs = {c.alpha_3: c.alpha_2.lower() for c in countries} | EXTRA_ALPHA2
    lines += [f'  {alpha3}: "{alpha2}",' for alpha3, alpha2 in sorted(pairs.items())]
    lines.append("};")
    target = Path(__file__).resolve().parents[2] / "frontend" / "src" / "three" / "isoCodes.ts"
    target.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    print(f"Wrote {len(countries)} countries to {target}")


if __name__ == "__main__":
    main()
